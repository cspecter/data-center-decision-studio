import {readFile,writeFile} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=async p=>await readFile(resolve(root,p),'utf8');
const strip=txt=>txt.replace(/^import .*?;\s*$/gm,'').replace(/\bexport\s+(?=(?:const|function|class)\b)/g,'');
const css=await read('src/styles.css');
const dataset=(await read('src/model-data.json')).replace(/</g,'\\u003c');
const fmdata=await read('src/fm-data.json');
const model=strip(await read('src/model.js'));
const inputs=strip(await read('src/inputs.js'));
const tooltips=strip(await read('src/tooltips.js'));
const forecast=strip(await read('src/reforecast.js'));
let app=strip(await read('src/app.js'));
app=app.replace("const DATA=await fetch('./src/model-data.json').then(r=>{if(!r.ok)throw Error('Missing model data');return r.json()});", "const DATA=JSON.parse(document.getElementById('embedded-workbook-data').textContent);");
if(/^import\s/m.test([model,inputs,tooltips,forecast,app].join('\n')))throw Error('An unresolved module import remains');
const all=`${model}\n${inputs}\n${tooltips}\nconst FM_DEFAULTS=${fmdata};\nconst FM=FM_DEFAULTS;\nconst workbookResults=results;\n${forecast}\n${app}`;
const html=`<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Data Center Decision Studio v0.4</title><style>${css}</style></head><body><div id="app"><div class="loading">Loading local financial workspace…</div></div><script id="embedded-workbook-data" type="application/json">${dataset}</script><script type="module">${all}</script></body></html>`;
await writeFile(resolve(root,'../Data_Center_Decision_Studio_GitHub_Ready_Preview.html'),html,'utf8');
console.log('Preview:',new TextEncoder().encode(html).length,'bytes');
